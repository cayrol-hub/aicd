const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

function row(finding: OptimizerFinding, language: Language): string {
    const t = TEXT[language];
    const saving =
        finding.estimatedSavingMinutesPerRun !== undefined ? t.perRun(finding.estimatedSavingMinutesPerRun) : t.unknown;
    return `| ${finding.job ? `\`${cell(finding.job)}\`` : finding.file ? `\`${cell(finding.file)}\`` : t.unknown} | ${cell(finding.title)} (${t.kinds[finding.kind]}) | ${saving} |`;
}

/** Markdown report: a table (job, finding, estimated saving) then the details and evidence of each finding. */
export function renderOptimizerReport(report: OptimizerReport, options: {language: Language}): string {
    const t = TEXT[options.language];
    const colon = options.language === "fr" ? " :" : ":";
    const parts = [`### ${t.title}`];
    if (report.findings.length === 0) {
        parts.push(t.none, `<sub>${t.history(report.pipelines, report.jobRuns)}</sub>`);
        return parts.join("\n\n");
    }
    parts.push(t.intro(report.findings.length, report.totalEstimatedSavingMinutesPerRun));
    parts.push(
        [
            `| ${t.columns.join(" | ")} |`,
            `| ${t.columns.map(() => "---").join(" | ")} |`,
            ...report.findings.map((finding) => row(finding, options.language))
        ].join("\n")
    );
    for (const finding of report.findings) {
        const lines = [`#### ${finding.title}`, "", finding.detail];
        if (finding.evidence.length > 0) {
            lines.push("", `<details><summary>${t.evidence}</summary>`, "");
            for (const item of finding.evidence) {
                lines.push(`- ${item.ref}${item.quote ? ` — \`${item.quote.replace(/`/g, "'").slice(0, 200)}\`` : ""}`);
            }
            lines.push("", "</details>");
        }
        parts.push(lines.join("\n"));
    }
    if (report.fix) {
        parts.push(
            [
                `**${t.fix(report.fix.branch)}**${colon} ${report.fix.summary}`,
                "",
                `${t.addresses}${colon} ${report.fix.addressed.map((finding) => finding.title).join(" · ")}`
            ].join("\n")
        );
    }
    parts.push(`<sub>${t.history(report.pipelines, report.jobRuns)} ${t.footer}</sub>`);
    return parts.join("\n\n");
}

/** Title of the issue proposed by a scheduled run. */
export function issueTitle(report: OptimizerReport, language: Language): string {
    return TEXT[language].issueTitle(report.findings.length, report.totalEstimatedSavingMinutesPerRun);
}

/** Description of the fix merge request. */
export function fixBody(fix: NonNullable<OptimizerReport["fix"]>, language: Language): string {
    const t = TEXT[language];
    return [
        t.fixIntro,
        "",
        fix.summary,
        "",
        ...fix.addressed.map((finding) => `- ${finding.title}${finding.job ? ` (\`${finding.job}\`)` : ""}`),
        "",
        `_${t.fixReview}_`
    ].join("\n");
}
