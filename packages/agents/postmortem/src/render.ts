function describe(d: Record<string, string>): string {
    const parts = [[d.service, d.version].filter(Boolean).join(" "), d.environment].filter(Boolean);
    return parts.length > 0 ? ` (${parts.join(", ")})` : "";
}

const utc = (iso: string) => `${iso.slice(0, 10)} ${iso.slice(11, 16)} UTC`;
const shortSha = (sha: string) => `\`${sha.slice(0, 12)}\``;

/** `45 min`, `2 h 5 min`. */
export function formatMinutes(minutes: number): string {
    if (minutes < 60) return `${minutes} min`;
    const hours = Math.floor(minutes / 60);
    const rest = minutes % 60;
    return rest === 0 ? `${hours} h` : `${hours} h ${rest} min`;
}

/** One line describing a timeline entry. */
export function timelineText(entry: TimelineEntry, language: Language): string {
    const t = TEXT[language].timeline;
    switch (entry.kind) {
        case "note":
            return `${entry.sourceKind ? `${entry.sourceKind}: ` : ""}${entry.data.text ?? ""}`;
        case "guard_verdict":
            return t.guard_verdict(
                entry.data,
                TEXT[language].verdict[entry.data.verdict ?? ""] ?? entry.data.verdict ?? ""
            );
        default:
            return t[entry.kind](entry.data);
    }
}

/** One paragraph on the correlation, for the incident timeline and the notification. */
export function correlationText(report: CorrelationReport, language: Language): string {
    const t = TEXT[language].correlation;
    if (!report.deployment) return t.none(report.lookbackHours);
    const d = report.deployment;
    const what = describe({
        ...(d.service ? {service: d.service} : {}),
        ...(d.version ? {version: d.version} : {}),
        environment: d.environment
    });
    const parts = [t.found(d.id, what, utc(d.startedAt))];
    if (report.suspects.length === 0) parts.push(t.noCommits);
    else {
        const list = report.suspects
            .slice(0, 5)
            .map((s) => `${s.sha.slice(0, 12)}${s.subject ? ` (${s.subject})` : ""}`)
            .join(", ");
        parts.push(t.commits(report.suspects.length, list));
    }
    return parts.join(" ");
}

/** Body of the issue proposed for an incident. */
export function renderCorrelationIssue(
    incident: IncidentRecord,
    report: CorrelationReport,
    language: Language
): string {
    const t = TEXT[language].issue;
    const colon = language === "fr" ? " :" : ":";
    const lines = [t.intro(incident.id), "", `- ${t.opened}${colon} ${utc(incident.openedAt)}`];
    if (incident.environment) lines.push(`- ${t.environment}${colon} ${incident.environment}`);
    if (incident.severity) lines.push(`- ${t.severity}${colon} ${TEXT[language].severity[incident.severity]}`);
    if (incident.url) lines.push(`- ${t.link}${colon} ${incident.url}`);
    lines.push("", `**${t.correlation}**${colon} ${correlationText(report, language)}`);
    if (report.suspects.length > 0) {
        lines.push("", `**${t.suspects}**${colon}`);
        for (const suspect of report.suspects.slice(0, 10)) {
            lines.push(
                `- ${shortSha(suspect.sha)}${suspect.subject ? ` ${suspect.subject}` : ""}${suspect.reason ? ` — ${suspect.reason}` : ""}`
            );
        }
    }
    lines.push("", `<sub>${t.footer}</sub>`);
    return lines.join("\n");
}

type ReportWithoutMarkdown = Omit<PostmortemReport, "markdown">;

/** Narrative written without the LLM, from the timeline only; every claim cites the entries it rests on. */
export function deterministicNarrative(report: ReportWithoutMarkdown, language: Language): Claim[] {
    const t = TEXT[language].narrative;
    const id = (kind: TimelineEntry["kind"]) => report.timeline.find((entry) => entry.kind === kind)?.id;
    const alert = id("alert_opened");
    const started = id("deployment_started");
    const rollback = id("rollback");
    const resolved = id("resolved");
    const cites = (...ids: (string | undefined)[]) => ids.filter((x): x is string => x !== undefined);
    const {durations} = report;

    const summary = [
        t.summary(
            report.title,
            utc(report.openedAt),
            report.environment,
            report.severity ? TEXT[language].severity[report.severity] : undefined
        )
    ];
    if (report.deploymentId && durations.detectMinutes !== undefined) {
        summary.push(t.afterDeployment(formatMinutes(Math.max(0, durations.detectMinutes)), report.deploymentId));
    }
    summary.push(
        durations.resolveMinutes !== undefined
            ? t.resolvedAfter(formatMinutes(durations.resolveMinutes))
            : t.notResolved
    );

    const claims: Claim[] = [
        {section: "summary", text: summary.join(" "), cites: cites(alert, started, resolved)},
        {
            section: "impact",
            text: [
                t.impact,
                ...(durations.resolveMinutes !== undefined ? [t.lasted(formatMinutes(durations.resolveMinutes))] : [])
            ].join(" "),
            cites: cites(alert, resolved)
        }
    ];
    if (report.deploymentId && started) {
        const commits = report.suspectCommits
            .slice(0, 3)
            .map((c) => `${shortSha(c.sha)}${c.subject ? ` (${c.subject})` : ""}`)
            .join(", ");
        claims.push({
            section: "root_cause",
            text: t.hypothesis(report.deploymentId, commits),
            cites: cites(started, alert)
        });
    } else {
        claims.push({section: "root_cause", text: t.noDeployment, cites: cites(alert)});
    }
    claims.push({section: "action_item", text: t.confirm, cites: cites(alert)});
    claims.push({section: "action_item", text: t.detection, cites: cites(started, alert)});
    if (report.deploymentId && !rollback)
        claims.push({section: "action_item", text: t.rollback, cites: cites(started)});
    return claims;
}

function durationLine(label: string, minutes: number | undefined, language: Language, note?: string): string {
    const colon = language === "fr" ? " :" : ":";
    const value = minutes === undefined ? TEXT[language].doc.unknown : formatMinutes(minutes);
    return `- ${label}${colon} ${value}${note ? ` (${note})` : ""}`;
}

function renderDurations(durations: Durations, language: Language): string {
    const t = TEXT[language].doc;
    return [
        durationLine(t.detect, durations.detectMinutes, language),
        durationLine(
            t.mitigate,
            durations.mitigateMinutes,
            language,
            durations.mitigatedBeforeAlert ? t.beforeAlert : undefined
        ),
        durationLine(t.resolve, durations.resolveMinutes, language)
    ].join("\n");
}

const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\n/g, " ");

/** Blameless markdown post-mortem: metadata, summary, impact, timeline, durations, hypothesis, action items. */
export function renderPostmortem(report: ReportWithoutMarkdown, options: {language: Language; runId?: string}): string {
    const t = TEXT[options.language].doc;
    const colon = options.language === "fr" ? " :" : ":";
    const cite = (claim: Claim) => ` [${claim.cites.join(", ")}]`;
    const section = (name: NarrativeSection) => {
        const claims = report.claims.filter((claim) => claim.section === name);
        if (claims.length === 0) return t.none;
        if (name === "action_item") return claims.map((claim) => `- [ ] ${claim.text}${cite(claim)}`).join("\n");
        return claims.map((claim) => `${claim.text}${cite(claim)}`).join("\n\n");
    };
    const meta: [string, string][] = [
        [t.date, report.openedAt.slice(0, 10)],
        ...(report.environment ? [[t.environment, report.environment] as [string, string]] : []),
        ...(report.severity
            ? [[t.severity, TEXT[options.language].severity[report.severity]] as [string, string]]
            : []),
        [t.status, report.resolvedAt ? t.resolved : t.ongoing],
        ...(report.deploymentId ? [[t.deployment, `\`${report.deploymentId}\``] as [string, string]] : []),
        ...(report.issueKey ? [[t.issue, report.issueKey] as [string, string]] : [])
    ];
    return [
        `# ${t.title}${colon} ${report.title}`,
        `> ${t.blameless}`,
        ["| | |", "| --- | --- |", ...meta.map(([key, value]) => `| ${key} | ${cell(value)} |`)].join("\n"),
        `## ${t.sections.summary}`,
        section("summary"),
        `## ${t.sections.impact}`,
        section("impact"),
        `## ${t.sections.timeline}`,
        [
            `| ${t.headers.join(" | ")} |`,
            "| --- | --- | --- |",
            ...report.timeline.map(
                (entry) =>
                    `| ${entry.id} | ${entry.at.slice(0, 16).replace("T", " ")} | ${cell(timelineText(entry, options.language))} |`
            )
        ].join("\n"),
        `## ${t.sections.durations}`,
        renderDurations(report.durations, options.language),
        `## ${t.sections.root_cause}`,
        section("root_cause"),
        `## ${t.sections.action_item}`,
        section("action_item"),
        `<sub>${t.footer(options.runId)}</sub>`,
        ""
    ].join("\n\n");
}
