// Generates docs/reference/configuration.md from the configuration schema (run after `pnpm build`).
import {writeFileSync} from "node:fs";
import {configJsonSchema, policiesJsonSchema} from "../packages/core/dist/index.js";
import {buildProgram} from "../packages/cli/dist/index.js";

function typeOf(schema) {
    if (schema.enum) return schema.enum.map((value) => `\`${value}\``).join(" \\| ");
    if (schema.anyOf) return schema.anyOf.map(typeOf).join(" or ");
    if (schema.type === "array") return `list of ${schema.items ? typeOf(schema.items) : "values"}`;
    if (
        schema.type === "object" &&
        schema.additionalProperties &&
        typeof schema.additionalProperties === "object" &&
        !schema.properties
    ) {
        return `map of ${typeOf(schema.additionalProperties)}`;
    }
    return schema.type ?? "value";
}

function rows(schema, prefix = []) {
    const out = [];
    for (const [key, child] of Object.entries(schema.properties ?? {})) {
        const path = [...prefix, key];
        const isSection =
            child.type === "object" &&
            child.properties &&
            Object.keys(child.properties).length > 0 &&
            !("type" in (child.properties ?? {}));
        if (isSection) {
            out.push(...rows(child, path));
            continue;
        }
        const fallback = child.default === undefined ? "" : `\`${JSON.stringify(child.default)}\``;
        out.push(
            `| \`${path.join(".")}\` | ${typeOf(child)} | ${fallback} | ${(child.description ?? "").replace(/\|/g, "\\|")} |`
        );
    }
    return out;
}

const table = (schema) =>
    ["| Key | Type | Default | Description |", "| --- | --- | --- | --- |", ...rows(schema)].join("\n");
const envName = (path) => `AICD_${path.replace(/\./g, "_").toUpperCase()}`;

writeFileSync(
    new URL("../docs/reference/configuration.md", import.meta.url),
    `<!-- Generated by scripts/generate-docs.mjs — do not edit. -->
# Configuration reference

\`.aicd.yaml\` at the root of the repository. Every key is optional. Priority, lowest to highest:
defaults → \`.aicd.yaml\` → environment variables → \`--set key=value\`, then capped by the organisation
policies (\`extends\`). Any scalar or list key can be set from the environment: \`agents.triage.autonomy\` →
\`${envName("agents.triage.autonomy")}\` (lists are comma-separated).

${table(configJsonSchema())}

# Organisation policies

Referenced with \`extends:\` (file path or https URL). A repository can lower these ceilings, never raise them.

${table(policiesJsonSchema())}
`
);
const program = buildProgram(() => {});
const sections = [];
const walk = (command, prefix) => {
    for (const sub of command.commands) {
        const name = `${prefix} ${sub.name()}`.trim();
        if (sub.commands.length > 0) walk(sub, name);
        else
            sections.push(
                `## \`aicd ${name}\`\n\n${sub.description()}\n\n\`\`\`text\n${sub.helpInformation().trim()}\n\`\`\``
            );
    }
};
walk(program, "");
writeFileSync(
    new URL("../docs/reference/cli.md", import.meta.url),
    `<!-- Generated by scripts/generate-docs.mjs — do not edit. -->\n# CLI reference\n\nExit codes: \`0\` OK · \`1\` a gate failed (\`--strict\`, \`quarantine check\`, \`replay --min-accuracy\`) · \`2\` invalid configuration · \`3\` internal error (only with \`AICD_FAIL_ON_INTERNAL_ERROR=true\`). Logs go to stderr; stdout carries command output.\n\n${sections.join("\n\n")}\n`
);
console.log("docs/reference/configuration.md and docs/reference/cli.md written");
